import dev.example.soledom.core.config.Messages;
import dev.example.soledom.core.config.SoledomConfig;
import dev.example.soledom.core.listeners.EntityLifecycleListener;
import dev.example.soledom.core.listeners.InteractionListener;
import dev.example.soledom.core.listeners.ResourcePackListener;
import dev.example.soledom.core.listeners.RootRemovalListener;
import dev.example.soledom.core.utils.RuntimeValidator;
import dev.example.soledom.loader.ContentLoader;
import dev.example.soledom.registry.ModelRegistry;
import dev.example.soledom.registry.RegisteredModel;
import dev.example.soledom.resourcepack.PackService;
import dev.example.soledom.runtime.ModelKeys;
import dev.example.soledom.runtime.ModelManager;
import dev.example.soledom.scheduler.BukkitSchedulerAdapter;
import dev.example.soledom.scheduler.FoliaSchedulerAdapter;
import dev.example.soledom.scheduler.SchedulerAdapter;

/** Plugin entry point: wires the services together and owns their lifecycle. */
public final class SoledomPlugin extends JavaPlugin {

    /** Example files copied on first start. Generated by us, free to use. */
    private static final List<String> EXAMPLES = List.of("models/example_golem.json",
            "animations/example_idle.json", "animations/example_rotate.json");

    private final Messages messages = new Messages();
    private final ContentLoader contentLoader = new ContentLoader();
    private final AtomicBoolean reloading = new AtomicBoolean();

    private volatile SoledomConfig settings;
    private ServerVersion serverVersion;
    private FeatureFlags features;
    private VersionAdapter adapter;
    private SchedulerAdapter scheduler;
    private ModelKeys keys;
    private ModelRegistry registry;
    private ModelManager manager;
    private AnimationEngine engine;
    private PackService packService;
    private SoledomAPI api;
    private volatile ContentLoader.LoadReport lastReport;

    @Override
    public void onEnable() {
        serverVersion = ServerVersion.parse(Bukkit.getMinecraftVersion());
        features = FeatureFlags.detect(serverVersion);
        getLogger().info("Server " + serverVersion + " | capabilities " + features);
        if (serverVersion.isNewerThanTested()) {
            getLogger().warning("Minecraft " + serverVersion + " is newer than the newest version this build was"
                    + " verified on (" + ServerVersion.NEWEST_TESTED + "). Running in capability-detection mode.");
        }
        if (!features.hasDisplayEntities()) {
            // LIMITATION: display entities are the rendering primitive; there is no reasonable fallback.
            getLogger().severe("This server has no display entities (Minecraft 1.19.4+ required). Disabling.");
            getServer().getPluginManager().disablePlugin(this);
            return;
        }

        saveDefaultConfig();
        copyExamplesOnFirstRun();
        settings = SoledomConfig.from(getConfig(), getLogger());
        messages.load(this);

        scheduler = features.hasFolia() ? new FoliaSchedulerAdapter(this) : new BukkitSchedulerAdapter(this);
        adapter = new ModernVersionAdapter(serverVersion, features, getLogger());
        keys = new ModelKeys(this);
        registry = new ModelRegistry();
        manager = new ModelManager(this, registry, adapter, scheduler, keys, this::settings);
        engine = new AnimationEngine(scheduler, adapter, this::settings);
        manager.setEngine(engine);
        packService = new PackService(getDataFolder().toPath(), registry, scheduler, adapter, this::settings,
                getLogger());

        // Startup load is synchronous on purpose: it runs before the server ticks, and persisted models in spawn
        // chunks need their definitions before they can be rebuilt. /soledom reload loads asynchronously.
        applyReport(contentLoader.load(getDataFolder().toPath()));

        registerListeners();
        registerCommand();

        api = new SoledomApiImpl(registry, manager, keys);
        Soledom.install(api);
        getServer().getServicesManager().register(SoledomAPI.class, api, this, ServicePriority.Normal);

        scheduler.runGlobal(manager::scanLoadedWorlds);
    }

    @Override
    public void onDisable() {
        if (manager != null) {
            manager.shutdown();
        }
        if (scheduler != null) {
            scheduler.cancelAll();
        }
        HandlerList.unregisterAll(this);
        getServer().getServicesManager().unregisterAll(this);
        Soledom.install(null);
    }

    /**
     * Reloads config, messages, models and animations. File IO runs async; the registry swap and model refresh
     * happen back on the global thread.
     *
     * @return false if a reload is already in progress
     */
    public boolean reload(@Nullable CommandSender sender) {
        if (!reloading.compareAndSet(false, true)) {
            return false;
        }
        try {
            reloadConfig();
            settings = SoledomConfig.from(getConfig(), getLogger());
            messages.load(this);
        } catch (RuntimeException e) {
            reloading.set(false);
            throw e;
        }
        Path dataFolder = getDataFolder().toPath();
        scheduler.runAsync(() -> {
            ContentLoader.LoadReport report;
            try {
                report = contentLoader.load(dataFolder);
            } catch (RuntimeException e) {
                getLogger().log(Level.SEVERE, "Reload failed", e);
                reloading.set(false);
                return;
            }
            scheduler.runGlobal(() -> {
                try {
                    ContentLoader.LoadReport applied = applyReport(report);
                    manager.refreshAll();
                    if (sender != null) {
                        reportTo(sender, applied);
                    }
                } finally {
                    reloading.set(false);
                }
            });
        });
        return true;
    }

    /** Validates against the server, swaps the registry and logs problems. Returns the effective report. */
    private ContentLoader.LoadReport applyReport(ContentLoader.LoadReport report) {
        List<String> errors = new ArrayList<>(report.errors());
        var valid = RuntimeValidator.validate(report.models(), errors);
        registry.replaceFileContent(valid, report.animations());
        ContentLoader.LoadReport effective = new ContentLoader.LoadReport(valid, report.animations(), errors,
                report.warnings());
        lastReport = effective;
        getLogger().info("Loaded " + valid.size() + " model(s) and " + report.animations().size()
                + " animation(s)" + (errors.isEmpty() ? "" : " with " + errors.size() + " error(s)"));
        errors.forEach(e -> getLogger().warning("  " + e));
        if (settings.debug()) {
            report.warnings().forEach(w -> getLogger().info("  [warning] " + w));
        } else if (!report.warnings().isEmpty()) {
            getLogger().info("  " + report.warnings().size() + " warning(s); enable debug to list them");
        }
        return effective;
    }

    private void reportTo(CommandSender sender, ContentLoader.LoadReport report) {
        messages.send(sender, "reload.done", Messages.ph("models", report.models().size()),
                Messages.ph("animations", report.animations().size()), Messages.ph("errors", report.errors().size()));
        int shown = 0;
        for (String error : report.errors()) {
            if (shown++ >= 10) {
                messages.send(sender, "reload.more-errors", Messages.ph("count", report.errors().size() - 10));
                break;
            }
            messages.send(sender, "reload.error-line", Messages.ph("error", error));
        }
    }

    private void registerListeners() {
        var pm = getServer().getPluginManager();
        pm.registerEvents(new EntityLifecycleListener(manager), this);
        pm.registerEvents(new InteractionListener(manager), this);
        pm.registerEvents(new ResourcePackListener(packService), this);
        try {
            pm.registerEvents(new RootRemovalListener(manager, keys), this);
        } catch (LinkageError e) {
            getLogger().info("EntityRemoveEvent unavailable; killed roots leave parts until the chunk unloads.");
        }
    }

    private void registerCommand() {
        PluginCommand command = getCommand("soledom");
        if (command == null) {
            getLogger().severe("Command 'soledom' missing from plugin.yml");
            return;
        }
        SoledomCommand executor = new SoledomCommand(this);
        command.setExecutor(executor);
        command.setTabCompleter(executor);
    }

    private void copyExamplesOnFirstRun() {
        Path models = getDataFolder().toPath().resolve(ContentLoader.MODELS_DIR);
        if (Files.exists(models)) {
            return;
        }
        for (String example : EXAMPLES) {
            Path target = getDataFolder().toPath().resolve(example);
            try (InputStream in = getResource("examples/" + example)) {
                if (in == null) {
                    continue;
                }
                Files.createDirectories(target.getParent());
                Files.copy(in, target);
            } catch (IOException e) {
                getLogger().log(Level.WARNING, "Could not copy example " + example, e);
            }
        }
        try {
            Files.createDirectories(getDataFolder().toPath().resolve(PackService.OVERLAY_DIR)
                    .resolve("assets/soledom/models/item"));
            Files.createDirectories(getDataFolder().toPath().resolve(PackService.OVERLAY_DIR)
                    .resolve("assets/soledom/textures/item"));
        } catch (IOException e) {
            getLogger().log(Level.WARNING, "Could not create pack overlay folders", e);
        }
    }

    // ---------------------------------------------------------------- accessors

    public @NotNull SoledomConfig settings() {
        return settings;
    }

    public @NotNull Messages messages() {
        return messages;
    }

    public @NotNull ServerVersion serverVersion() {
        return serverVersion;
    }

    public @NotNull FeatureFlags features() {
        return features;
    }

    public @NotNull SchedulerAdapter scheduler() {
        return scheduler;
    }

    public @NotNull ModelKeys keys() {
        return keys;
    }

    public @NotNull ModelRegistry registry() {
        return registry;
    }

    public @NotNull ModelManager manager() {
        return manager;
    }

    public @NotNull PackService packService() {
        return packService;
    }

    public @Nullable ContentLoader.LoadReport lastReport() {
        return lastReport;
    }

    public @NotNull List<RegisteredModel> modelsSorted() {
        return registry.ids().stream().map(registry::get).flatMap(java.util.Optional::stream).toList();
    }

    public void setDebug(boolean debug) {
        SoledomConfig c = settings;
        settings = new SoledomConfig(debug, c.animationTickRate(), c.maxAnimationDistance(), c.animateOnlyNearPlayers(),
                c.persistModels(), c.autoCleanup(), c.maxModelsPerChunk(), c.pack());
    }
}
