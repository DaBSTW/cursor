import org.bukkit.Bukkit;
import org.bukkit.command.CommandSender;
import org.bukkit.command.PluginCommand;
import org.bukkit.event.HandlerList;
import org.bukkit.plugin.ServicePriority;
import org.bukkit.plugin.java.JavaPlugin;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import dev.example.soledom.animation.AnimationEngine;
import dev.example.soledom.api.Soledom;
import dev.example.soledom.api.SoledomAPI;
import dev.example.soledom.compat.FeatureFlags;
import dev.example.soledom.compat.ModernVersionAdapter;
